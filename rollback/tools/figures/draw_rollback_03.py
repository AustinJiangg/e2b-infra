from common import *  # noqa: F401,F403


def f03_1():
    d = Diagram()
    d.header("为什么另做一套：原生要停沙箱、成本随虚机规格，本方案绑定沙箱生命周期换来原地回滚",
             "目标场景是高频、低延迟、沙箱不能中断。原生 pause / resume 的停沙箱、重建进程、换回工作集来自它的语义本身；"
             "本方案放弃产物自足性与账本持久化，换来零拷贝封存、原地回滚，以及只随回退跨度增长的成本。",
             legend=[("flow", "先后顺序"), ("warn", "与目标场景冲突的代价")])

    d.section(1, "同样是“保存一个时刻、之后回到它”，两条路径各做什么", highlight="本图重点")
    c = d.compare([("原生 pause / resume", "Pause、Checkpoint 两个 RPC", "coral"),
                   ("本方案 checkpoint / restore", "活沙箱上的高频回退", "teal")])
    c.states("保存之后的沙箱", [("沙箱被停掉", "导出磁盘增量要先摘出写层、停掉沙箱、等 NBD 设备释放"),
                              ("沙箱继续运行", "同一个 Firecracker 进程，宿主资源都在")])
    c.row("产物", [("快照进持久化存储", "原生负责迁移、持久化和崩溃恢复"),
                  ("产物在宿主本地", "内存每代只存本代脏页；磁盘封存是改名，零数据搬运")],
          links=[None, None])
    c.row("恢复做什么", [("新建 Firecracker 进程", "再靠缺页把整个工作集换回内存"),
                       ("原地回滚", "按页写回回滚集；进程、KVM fd、tap、网络槽位、NBD 设备一个都不重建")],
          links=[("warn", "要新建进程"), "flow"])
    c.row("代价取决于", [("虚机多大", "回退只改了 40 MiB 的沙箱，和改了 2 GiB 的沙箱，花的时间几乎一样"),
                       ("回退跨度", "成本只与改动量挂钩；唯一保留的固定开销是全量根")],
          links=[None, None])
    c.summary("对照目标场景", [
        ("沙箱不能中断", [("要停沙箱、新建进程", "bad"), ("沙箱不中断", "good")]),
        ("高频：单次改动量通常很小", [("改动小时省不下任何东西", "bad"), ("改动小，代价就小", "good")]),
        ("迁移、持久化、崩溃恢复", [("由原生负责", "good"), ("明确不做，交给原生 snapshot", "bad")]),
        ("orchestrator 或宿主重启之后", ["快照仍在持久化存储里", ("checkpoint 全部失效", "bad")]),
    ])
    c.end()
    d.footer("注：ARM 适配基线上原生的脏页判据退化（读也算脏），已在第 14、15 章单独修复；修复后上面两条代价不变，"
             "因为它们来自停沙箱、重建进程、换回工作集的语义，与判据是否精确无关。恢复的逐步对比见图 09-1，两条路径怎么交替使用见图 15-1。")
    d.save(out("rollback", "03-1-为什么另做一套"))


if __name__ == "__main__":
    f03_1()
